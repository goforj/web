const (
	// indexCacheFormatVersion invalidates persisted analysis whenever its inputs or representation change.
	indexCacheFormatVersion = 4
	// indexCacheMaximumSize bounds memory consumed by a corrupt or unexpectedly large cache entry.
	indexCacheMaximumSize = 64 << 20
	// indexCacheMagic separates this binary cache from generated JSON artifacts and future formats.
	indexCacheMagic = "goforj-webindex-cache-v4\n"
	// indexCacheEnvelopeLengthBytes stores three uint32 section lengths before cache payloads.
	indexCacheEnvelopeLengthBytes = 12
)

const (
	// indexCacheManifestArtifact identifies the canonical API index bytes independently of their destination path.
	indexCacheManifestArtifact = "manifest"
	// indexCacheDiagnosticsArtifact identifies the diagnostic projection bytes independently of their destination path.
	indexCacheDiagnosticsArtifact = "diagnostics"
	// indexCacheOpenAPIArtifact identifies the OpenAPI projection bytes independently of their destination path.
	indexCacheOpenAPIArtifact = "openapi"
)

// indexCacheRecord contains everything needed to return and publish one successful analysis without loading Go packages again.
type indexCacheRecord struct {
	Version      int                          `json:"version"`
	InputHash    string                       `json:"input_hash"`
	ManifestData []byte                       `json:"manifest_data"`
	Manifest     indexCacheManifestShape      `json:"manifest"`
	Artifacts    []indexCacheArtifact         `json:"artifacts"`
	TypedState   *typedSchemaIncrementalState `json:"-"`
}

// indexCacheEnvelope separates exact artifacts from incremental types so changed builds decode only the state they need.
type indexCacheEnvelope struct {
	inputHash string
	record    []byte
	typed     []byte
}

// indexCacheArtifact binds exact generated bytes to a stable role rather than a staging-directory path.
type indexCacheArtifact struct {
	Role string `json:"role"`
	Data []byte `json:"data"`
}

// indexCacheManifestShape retains runtime types and non-JSON state without duplicating canonical manifest values.
type indexCacheManifestShape struct {
	Operations []indexCacheOperationShape `json:"operations"`
	Schemas    [][]indexCacheValueShape   `json:"schemas"`
}

// indexCacheOperationShape retains omitted empty slices, schema runtime types, and private middleware provenance.
type indexCacheOperationShape struct {
	MiddlewarePresent           bool                     `json:"middleware_present,omitempty"`
	PathParamsPresent           bool                     `json:"path_params_present,omitempty"`
	QueryParamsPresent          bool                     `json:"query_params_present,omitempty"`
	HeadersPresent              bool                     `json:"headers_present,omitempty"`
	CookiesPresent              bool                     `json:"cookies_present,omitempty"`
	ResponsesPresent            bool                     `json:"responses_present,omitempty"`
	MetadataTagsPresent         bool                     `json:"metadata_tags_present,omitempty"`
	MiddlewareProvenancePresent bool                     `json:"middleware_provenance_present,omitempty"`
	MiddlewareProvenance        []middlewareProvenance   `json:"middleware_provenance"`
	Body                        []indexCacheValueShape   `json:"body,omitempty"`
	Responses                   [][]indexCacheValueShape `json:"responses"`
}

// indexCacheValueShape identifies one JSON-decoded value that needs its original concrete Go type restored.
type indexCacheValueShape struct {
	Path []indexCachePathSegment `json:"path,omitempty"`
	Kind string                  `json:"kind"`
}

// indexCachePathSegment navigates either one schema map key or one array index.
type indexCachePathSegment struct {
	Key   string `json:"key,omitempty"`
	Index int    `json:"index,omitempty"`
	Array bool   `json:"array,omitempty"`
}

